export function quickExamTranslate(locale, text) {
  if (locale !== 'ar') return text
  const value = String(text).trim()
  if (quickExamAr[value]) return quickExamAr[value]
  const patterns = [
    [/^Question (\d+) of (\d+)$/, (a, b) => `السؤال ${a} من ${b}`],
    [/^Question (\d+)$/, a => `السؤال ${a}`], [/^Attempt (\d+)$/, a => `المحاولة ${a}`],
    [/^(\d+) questions$/, a => `${a} أسئلة`], [/^(\d+) answered$/, a => `${a} مُجاب عنه`],
    [/^(\d+) unanswered$/, a => `${a} غير مُجاب عنه`], [/^(\d+) marked$/, a => `${a} محدد للمراجعة`],
    [/^Warning (\d+) of (\d+)$/, (a, b) => `التحذير ${a} من ${b}`],
    [/^(\d+) minutes (\d+) seconds remaining$/, (a, b) => `متبقي ${a} دقيقة و${b} ثانية`],
    [/^(\d+) min$/, a => `${a} دقيقة`],
  ]
  for (const [pattern, render] of patterns) { const match = value.match(pattern); if (match) return render(...match.slice(1)) }
  return text
}
